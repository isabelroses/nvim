          shell = vim.fn.executable("fish") == 1 and "fish" or nil,
        },
        lazygit = {
          enabled = true,
          -- use lazygit's own config and the terminal palette, not colours derived from nvim highlights
          configure = false,
        },
        picker = {
          -- fzf-lua handles vim.ui.select, this is only here for the explorer
          enabled = false,
          -- plain indentation instead of tree guide lines
          icons = { tree = { vertical = "  ", middle = "  ", last = "  " } },
          sources = {
            explorer = {
              hidden = true,
              ignored = true,
              diagnostics = false,
              layout = {
                hidden = { "input" }, -- press `/` to search
                layout = { width = 30, min_width = 30 },
              },
              win = {
                list = {
                  keys = {
                    -- the picker maps <c-n> to list_down, take it back so it toggles the explorer
                    ["<c-n>"] = "close",
                    -- the default `/` shows the search box but never hides it again
                    ["/"] = "toggle_input",
                  },
                },
                input = {
                  keys = { ["<c-n>"] = { "close", mode = { "n", "i" } } },
                },
              },
            },
          },
        },

        -- undo defaults
        notifier = { enabled = false },
        scope = { enabled = false },
        scroll = { enabled = false },
        statuscolumn = { enabled = false },
        words = { enabled = false },
      }

      snacks.setup(opts)

      local map = function(mode, lhs, rhs, desc)
        vim.keymap.set(mode, lhs, rhs, { silent = true, desc = desc })
      end

      map("n", "<C-N>", snacks.explorer.open, "toggle file explorer")
      map({ "n", "t" }, "<c-t>", snacks.terminal.toggle, "toggle terminal")
      map("n", "<leader>gg", snacks.lazygit.open, "open lazygit")
    end,
  },
